"""Build compact world geometry for the 'forsta-amerikanerna' globe from Natural Earth (public domain).

Output: JS file assigning window.FA_GEO with delta-encoded rings, absolute [lon, lat] in 1/q degrees.
Natural Earth polygons are already split at the antimeridian, so rings can be drawn directly on an
equirectangular canvas.
Usage: python3 -I build_geo.py <src_dir> <out_js>
"""
import json, sys
from shapely.geometry import shape, Polygon, MultiPolygon

SRC, OUT = sys.argv[1], sys.argv[2]
Q = 50  # units per degree

def load(name):
    return json.load(open(f"{SRC}/{name}.geojson", encoding="utf-8"))["features"]

def polys(g):
    if g.is_empty:
        return []
    if isinstance(g, Polygon):
        return [g]
    if isinstance(g, MultiPolygon):
        return list(g.geoms)
    out = []
    for p in getattr(g, "geoms", []):
        out += polys(p)
    return out

def encode(features, tol, min_area, keep=lambda p: True):
    rings_out, npts = [], 0
    for f in features:
        if not keep(f["properties"]):
            continue
        g = shape(f["geometry"])
        if not g.is_valid:
            g = g.buffer(0)
        for p in polys(g.simplify(tol, preserve_topology=True)):
            if p.area < min_area:
                continue
            for ring in [p.exterior] + list(p.interiors):
                q = [(round(x * Q), round(y * Q)) for x, y in ring.coords]
                dq = [q[0]] + [c for i, c in enumerate(q[1:], 1) if c != q[i - 1]]
                if len(dq) < 4:
                    continue
                nums = [dq[0][0], dq[0][1]]
                for i in range(1, len(dq)):
                    nums += [dq[i][0] - dq[i - 1][0], dq[i][1] - dq[i - 1][1]]
                rings_out.append(",".join(map(str, nums)))
                npts += len(dq)
    return ";".join(rings_out), npts

land_s, n1 = encode(load("ne_50m_land"), 0.03, 0.002)
lake_s, n2 = encode(load("ne_50m_lakes"), 0.05, 0.05, keep=lambda p: p.get("scalerank", 9) <= 2)
deep_s, n3 = encode(load("ne_10m_bathymetry_K_200"), 0.1, 0.03)

meta = {
    "q": Q,
    "source": "Natural Earth (public domain, naturalearthdata.com): ne_50m_land, ne_50m_lakes (scalerank<=2), ne_10m_bathymetry_K_200",
    "note": "Rings are [lon, lat] in 1/q degree units; first pair absolute, then deltas. Rings separated by ';'.",
}
js = "/* Generated by build_geo.py from Natural Earth (public domain). Do not edit by hand. */\n"
js += "window.FA_GEO = " + json.dumps({"meta": meta, "land": land_s, "lakes": lake_s, "deep": deep_s}, separators=(",", ":")) + ";\n"
open(OUT, "w", encoding="utf-8").write(js)
print("points land/lakes/deep:", n1, n2, n3, "bytes:", len(js))
